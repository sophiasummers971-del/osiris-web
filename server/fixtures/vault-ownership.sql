-- Synthetic schema for the four Vault ownership boundaries, not a Supabase restore.
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
create role osiris_server nologin bypassrls;
create schema auth;
create schema extensions;
create extension pgcrypto with schema extensions;
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
grant usage on schema public, auth, extensions to anon, authenticated, service_role, osiris_server;
grant execute on function auth.uid() to anon, authenticated, service_role, osiris_server;
create table public.osiris_operators (
 id bigint generated by default as identity (start with 1000) primary key,
 external_id text unique, auth_user_id uuid unique,
 display_name text, email text, role text not null default 'operator' check (role in ('operator','admin')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.security_cases (
 id bigint generated by default as identity (start with 1000) primary key,
 owner_id bigint not null references public.osiris_operators(id),
 title text not null, summary text, severity text not null default 'medium',
 status text not null default 'open', confidence integer not null default 50,
 created_at timestamptz not null default now(),updated_at timestamptz not null default now()
);
create table public.evidence_records (
 id bigint generated by default as identity (start with 1000) primary key,
 case_id bigint not null references public.security_cases(id),
 owner_id bigint not null references public.osiris_operators(id),
 label text not null, source_type text not null, source_reference text, content_hash text,
 notes text,captured_at timestamptz not null default now(),created_at timestamptz not null default now(),
 storage_bucket text,storage_path text unique,original_filename text,mime_type text,file_size_bytes bigint,uploaded_at timestamptz
);
create table public.case_audit_events (
 id bigint generated by default as identity (start with 1000) primary key,
 case_id bigint not null references public.security_cases(id),
 operator_id bigint not null references public.osiris_operators(id),
 action text not null,details jsonb not null default '{}',created_at timestamptz not null default now(),
 previous_event_hash text,event_hash text unique
);
grant select,insert,update,delete on all tables in schema public to anon,authenticated;
grant all on all tables in schema public to service_role,osiris_server;
grant usage,select on all sequences in schema public to anon,authenticated,service_role,osiris_server;
alter table public.osiris_operators enable row level security;
alter table public.security_cases enable row level security;
alter table public.evidence_records enable row level security;
alter table public.case_audit_events enable row level security;
CREATE OR REPLACE FUNCTION public.seal_audit_event()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  perform pg_advisory_xact_lock(new.case_id);

  select event_hash
    into new.previous_event_hash
  from public.case_audit_events
  where case_id = new.case_id
  order by id desc
  limit 1;

  new.event_hash := encode(
    extensions.digest(
      concat_ws(
        '|',
        new.case_id::text,
        new.operator_id::text,
        new.action,
        new.details::text,
        coalesce(new.previous_event_hash, ''),
        new.created_at::text
      ),
      'sha256'
    ),
    'hex'
  );

  return new;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.prevent_vault_mutation()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
begin
  raise exception '% records are append-only', tg_table_name;
end;
$function$
;
CREATE TRIGGER seal_case_audit_event BEFORE INSERT ON public.case_audit_events FOR EACH ROW EXECUTE FUNCTION seal_audit_event();
CREATE TRIGGER protect_evidence_records BEFORE DELETE OR UPDATE ON public.evidence_records FOR EACH ROW EXECUTE FUNCTION prevent_vault_mutation();
CREATE TRIGGER protect_case_audit_events BEFORE DELETE OR UPDATE ON public.case_audit_events FOR EACH ROW EXECUTE FUNCTION prevent_vault_mutation();
